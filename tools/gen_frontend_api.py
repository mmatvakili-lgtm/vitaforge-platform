"""Generates the frontend's typed API contract from the OpenAPI spec (single source of truth).
Outputs: frontend/src/lib/api/generated.ts and frontend/src/messages/safety.generated.json.
Run:  python tools/gen_frontend_api.py        (a backend test fails if the committed output is stale)"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
SPEC = ROOT / "docs/02-architecture/07-OPENAPI-SPECIFICATION.yaml"
OUT_TS = ROOT / "frontend/src/lib/api/generated.ts"
OUT_MSG = ROOT / "frontend/src/messages/safety.generated.json"


def ts(x, S):
    if "$ref" in x:
        return x["$ref"].split("/")[-1]
    if "const" in x:
        return json.dumps(x["const"])
    if "enum" in x:
        return " | ".join(json.dumps(v) for v in x["enum"])
    for k in ("oneOf", "anyOf"):
        if k in x:
            return " | ".join(ts(y, S) for y in x[k])
    t = x.get("type")
    nullable = x.get("nullable") or (isinstance(t, list) and "null" in t)
    if isinstance(t, list):
        t = next((y for y in t if y != "null"), None)
    if t == "array":
        r = f"Array<{ts(x['items'], S)}>"
    elif t == "object" or "properties" in x:
        props = x.get("properties")
        if not props:
            r = "Record<string, unknown>"
        else:
            req = set(x.get("required", []))
            r = "{ " + "; ".join(f"{json.dumps(k)}{'' if k in req else '?'}: {ts(v, S)}" for k, v in props.items()) + " }"
    elif t in ("integer", "number"):
        r = "number"
    elif t == "boolean":
        r = "boolean"
    elif t == "string":
        r = "string"
    else:
        r = "unknown"
    return f"({r}) | null" if nullable else r


def ref_name(x):
    return x["$ref"].split("/")[-1] if x and "$ref" in x else None


def build():
    d = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    S = d["components"]["schemas"]
    lines = ["// GENERATED by tools/gen_frontend_api.py from the OpenAPI spec. DO NOT EDIT.", ""]
    for name, sch in S.items():
        lines.append(f"export type {name} = {ts(sch, S)};")
    ops, opmap = {}, []
    for path, item in d["paths"].items():
        for method, op in item.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            oid = op.get("x-id") or None
            params = op.get("parameters", [])
            pp = [p["name"] for p in params if p["in"] == "path"]
            qp = {p["name"]: ts(p["schema"], S) for p in params if p["in"] == "query"}
            body = ref_name(op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema"))
            succ = next(c for c in op["responses"] if c.startswith("2"))
            rs = op["responses"][succ].get("content", {}).get("application/json", {}).get("schema")
            res = ts(rs, S) if rs else "void"
            oid = oid or op["operationId"]
            ops[oid] = dict(method=method.upper(), path=path, secured=bool(op.get("security", d.get("security"))), success=int(succ),
                            errors=sorted(int(c) for c in op["responses"] if not c.startswith("2")))
            opmap.append((oid, body, res, pp, qp))
    lines += ["", "export interface OpTypes {"]
    for oid, body, res, pp, qp in opmap:
        q = "{ " + "; ".join(f"{k}?: {v}" for k, v in qp.items()) + " }" if qp else "Record<string, never>"
        p = "{ " + "; ".join(f"{k}: string" for k in pp) + " }" if pp else "Record<string, never>"
        lines.append(f"  {json.dumps(oid)}: {{ body: {body or 'undefined'}; res: {res}; path: {p}; query: {q} }};")
    lines += ["}", "", "export type OpId = keyof OpTypes;", "",
              "export const OPERATIONS: Record<OpId, { method: string; path: string; secured: boolean; success: number; errors: number[] }> = "
              + json.dumps(ops, indent=2) + ";", ""]
    from safety_core.explain import TEXT
    return "\n".join(lines), json.dumps({"fa": {k: v["fa"] for k, v in TEXT.items()}, "en": {k: v["en"] for k, v in TEXT.items()}}, ensure_ascii=False, indent=1) + "\n"


if __name__ == "__main__":
    t, m = build()
    OUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.write_text(t, encoding="utf-8", newline="\n")
    OUT_MSG.write_text(m, encoding="utf-8", newline="\n")
    print("ok", len(t.splitlines()), "lines")
